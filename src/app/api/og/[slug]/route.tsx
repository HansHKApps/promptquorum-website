import { ImageResponse } from 'next/og'
import fs from 'fs'
import path from 'path'
import ogIndex from '@/generated/og-index.json'
import type { Language } from '@/lib/blog/blogContent'

export const runtime = 'nodejs'

export async function GET(request: Request, { params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params

  // Extract language from query param, default to 'en'
  const url = new URL(request.url)
  const lang = (url.searchParams.get('lang') || 'en') as Language
  const validLangs: Language[] = ['en', 'de', 'fr', 'ja', 'zh', 'es', 'pt', 'ar', 'ko']
  const selectedLang = validLangs.includes(lang) ? lang : 'en'

  // Title + intro per slug and language, generated by scripts/generate-og-index.mjs
  // (lookup order: prompt-engineering → local-llms → power-local-llm → prompt-bites →
  // smart-home → balcony-solar → frameworks; first match wins). Importing the full
  // content barrels here pushed the function over Vercel's 250 MB limit.
  const entry = (ogIndex as Record<string, Partial<Record<Language, [string, string]>>>)[slug]
  const pair = entry?.[selectedLang] || entry?.en
  const article: { title?: string; intro?: string } | undefined = pair ? { title: pair[0], intro: pair[1] } : undefined

  if (!article) {
    return new Response('Not Found', { status: 404 })
  }
  const title = article.title
  const intro = article.intro

  return new ImageResponse(
    (
      <div
        style={{
          width: '1200px',
          height: '675px',
          display: 'flex',
          flexDirection: 'column',
          justifyContent: 'space-between',
          background: 'linear-gradient(135deg, #6750A4 0%, #7D5260 100%)',
          padding: '60px',
          fontFamily: selectedLang === 'ar' ? 'Beiruti' : 'Plus Jakarta Sans, system-ui, sans-serif',
          direction: selectedLang === 'ar' ? 'rtl' : 'ltr',
          color: '#FFFFFF',
        }}
      >
        {/* Top branding */}
        <div style={{ display: 'flex', flexDirection: selectedLang === 'ar' ? 'row-reverse' : 'row', justifyContent: 'space-between', alignItems: 'center' }}>
          <div style={{ fontSize: '20px', fontWeight: '700', letterSpacing: '0.1em' }}>
            PROMPTQUORUM
          </div>
          <div style={{ fontSize: '14px', opacity: 0.8 }}>Prompt Engineering Guide</div>
        </div>

        {/* Main content */}
        <div
          style={{
            display: 'flex',
            flexDirection: 'column',
            justifyContent: 'center',
            flex: 1,
          }}
        >
          {/* Title */}
          <h1
            style={{
              margin: '0 0 20px 0',
              fontSize: '52px',
              fontWeight: '700',
              lineHeight: '1.2',
              maxWidth: '100%',
              wordWrap: 'break-word',
              textAlign: selectedLang === 'ar' ? 'right' : 'left',
            }}
          >
            {title}
          </h1>

          {/* Intro/description */}
          <p
            style={{
              margin: '0',
              fontSize: '18px',
              lineHeight: '1.5',
              opacity: 0.95,
              maxWidth: '100%',
              display: '-webkit-box',
              WebkitLineClamp: 2,
              WebkitBoxOrient: 'vertical',
              overflow: 'hidden',
              textAlign: selectedLang === 'ar' ? 'right' : 'left',
            }}
          >
            {intro}
          </p>
        </div>

        {/* Bottom decoration */}
        <div
          style={{
            display: 'flex',
            flexDirection: selectedLang === 'ar' ? 'row-reverse' : 'row',
            justifyContent: 'space-between',
            alignItems: 'center',
            fontSize: '12px',
            opacity: 0.7,
          }}
        >
          <span>promptquorum.com</span>
          <span>•</span>
          <span>Learn Prompt Engineering</span>
        </div>
      </div>
    ),
    {
      width: 1200,
      height: 675,
      fonts: selectedLang === 'ar' ? [
        {
          name: 'Beiruti',
          data: fs.readFileSync(path.join(process.cwd(), 'public/fonts/Beiruti-Regular.ttf')),
          weight: 400,
          style: 'normal',
        },
        {
          name: 'Beiruti',
          data: fs.readFileSync(path.join(process.cwd(), 'public/fonts/Beiruti-Bold.ttf')),
          weight: 700,
          style: 'normal',
        },
      ] : undefined,
      headers: {
        'Content-Type': 'image/png',
        'Cache-Control': 'public, max-age=86400, s-maxage=31536000, immutable',
      },
    },
  )
}
