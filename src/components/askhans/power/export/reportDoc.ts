// Power Mode — the finished document: the AI-written body plus everything that makes it a shareable
// report (title, date, what the visitor entered, how it was made, PromptQuorum references, disclaimer).
// The labels arrive already translated (from the copy dictionaries); this file has no language logic.

/** "What PromptQuorum is" + real-size numbers, closing block of every report (data from the server, labels already localized). */
export interface ReportOverview {
  title: string
  blurb: string
  tiles: { label: string; value: string }[]
  links: { label: string; href: string }[]
}

export interface ReportLabels {
  /** "Generated by Ask Hans Power Mode" */
  generatedBy: string
  /** "Date" */
  dateLabel: string
  /** "Your inputs" */
  inputsHeading: string
  /** "How this report was made" */
  howHeading: string
  /** one paragraph, plain text */
  howText: string
  /** "More on PromptQuorum" */
  referencesHeading: string
  /** "Automatically generated" */
  autoNoticeHeading: string
  /** "made by an AI system, no human has reviewed it" */
  autoNotice: string
  /** "Legal notice and disclaimer" */
  disclaimerHeading: string
  /** lead paragraph of the legal notice */
  disclaimerText: string
  /** the numbered points of the legal notice */
  disclaimerPoints: string[]
  /** link text to the Ask Hans page, e.g. "Create your own report with Ask Hans" */
  createOwn: string
  /** the product name as a link label ("Ask Hans") */
  askHansName: string
}

export interface ReportReference {
  label: string
  /** absolute https URL */
  url: string
}

export interface ReportDoc {
  title: string
  processLabel: string
  /** already formatted for the report language */
  dateText: string
  lang: string
  dir: 'ltr' | 'rtl'
  /** "Label: value" lines describing the visitor's answers */
  inputs: string[]
  /** markdown written by the AI */
  body: string
  references: ReportReference[]
  /** closing overview block; absent when the server could not provide it */
  overview?: ReportOverview
  /** absolute URL of the Ask Hans page (in the report language) */
  askHansUrl: string
  /** absolute URL of the site root */
  siteUrl: string
  /** file name without extension (date, number, topic); see fileName.ts */
  fileBase?: string
  labels: ReportLabels
}

function overviewMarkdown(o?: ReportOverview): string[] {
  if (!o) return []
  return [`## ${o.title}`, '', o.blurb, '', ...o.tiles.map((t) => `- ${t.label}: ${t.value}`), '', ...o.links.map((k) => `- [${k.label}](${k.href})`), '']
}

/** The whole report as markdown: used by "Download .md" and (without the markup) by "Copy". */
export function buildMarkdown(doc: ReportDoc): string {
  const l = doc.labels
  return [
    `# ${doc.title}`,
    '',
    `*${doc.processLabel} · ${l.dateLabel}: ${doc.dateText} · ${l.generatedBy}*`,
    '',
    `[${l.createOwn}](${doc.askHansUrl}) · [promptquorum.com](${doc.siteUrl})`,
    '',
    `**${l.autoNoticeHeading}.** ${l.autoNotice}`,
    '',
    `## ${l.inputsHeading}`,
    '',
    ...doc.inputs.map((x) => `- ${x}`),
    '',
    doc.body.trim(),
    '',
    `## ${l.howHeading}`,
    '',
    l.howText,
    '',
    `## ${l.referencesHeading}`,
    '',
    ...doc.references.map((r) => `- [${r.label}](${r.url})`),
    '',
    `## ${l.disclaimerHeading}`,
    '',
    l.disclaimerText,
    '',
    ...l.disclaimerPoints.map((x, i) => `${i + 1}. ${x}`),
    '',
    ...overviewMarkdown(doc.overview),
    '',
    `[${l.createOwn}](${doc.askHansUrl}) · [promptquorum.com](${doc.siteUrl})`,
    '',
  ].join('\n')
}

/** Safe file name stem: letters/digits of any script, dashes; never empty. */
export function fileStem(doc: ReportDoc): string {
  if (doc.fileBase) return doc.fileBase
  const base = `promptquorum-${doc.processLabel}`.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, '-').replace(/^-+|-+$/g, '')
  return base || 'promptquorum-report'
}

