// Lightweight extract of the content barrels (dateModified/lastFactChecked/
// publishDate, hasSections, per-language langs, section images) generated by
// scripts/generate-content-metadata.mjs — NOT the barrels themselves. See
// that script for why: this route only ever needs a few small fields per
// article, but the barrels are megabytes of full article bodies each.
import contentMetadata from '@/generated/content-metadata.json'

export type ClusterMetadata = {
  dateModified: string | null
  lastFactChecked: string | null
  publishDate: string | null
  hasSections: boolean
  langs: string[]
  images: Array<{ url: string; title?: string }>
}
export type BlogMetadata = { lastmod: string; langs: string[]; images: Array<{ url: string; title?: string }> }
export const metadata = contentMetadata as unknown as {
  'local-llms': Record<string, ClusterMetadata>
  'prompt-engineering': Record<string, ClusterMetadata>
  'power-local-llm': Record<string, ClusterMetadata>
  'prompt-bites': Record<string, ClusterMetadata>
  'smart-home': Record<string, ClusterMetadata>
  'balcony-solar': Record<string, ClusterMetadata>
  blog: Record<string, BlogMetadata>
}

export const BASE = 'https://www.promptquorum.com'

