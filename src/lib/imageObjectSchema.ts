import imageDimensions from '@/data/image-dimensions.json'

const BASE_URL = 'https://www.promptquorum.com'

type Dimensions = { width?: number; height?: number; encodingFormat?: string }

const registry = imageDimensions as Record<string, Dimensions>

export function toAbsImageUrl(imagePath: string): string {
  if (imagePath.startsWith('http')) return imagePath
  if (imagePath.startsWith('/')) return `${BASE_URL}${imagePath}`
  return `${BASE_URL}/images/${imagePath}`
}

/**
 * Builds a schema.org ImageObject for an article image, including
 * contentUrl, encodingFormat, and real width/height sourced from
 * src/data/image-dimensions.json (generated by
 * scripts/generate-image-dimensions.mjs from each file's actual SVG
 * viewBox / JPEG header — never invented). width/height/encodingFormat
 * are omitted if the image isn't in the registry (e.g. added after the
 * last `npm run generate:image-dimensions` run).
 */
export function buildImageObject(
  imagePath: string,
  opts: { caption?: string } = {}
): Record<string, unknown> {
  const absUrl = toAbsImageUrl(imagePath)
  const normalizedPath = imagePath.startsWith('/') ? imagePath : `/images/${imagePath}`
  const dims = registry[normalizedPath]

  return {
    '@type': 'ImageObject',
    url: absUrl,
    contentUrl: absUrl,
    ...(dims?.width && dims?.height && { width: dims.width, height: dims.height }),
    ...(dims?.encodingFormat && { encodingFormat: dims.encodingFormat }),
    ...(opts.caption && { name: opts.caption.substring(0, 125), description: opts.caption }),
    creator: { '@type': 'Person', name: 'Hans Kuepper' },
    copyrightHolder: { '@type': 'Organization', name: 'PromptQuorum', url: BASE_URL },
    license: 'https://www.promptquorum.com/image-license',
    acquireLicensePage: 'https://www.promptquorum.com/image-license',
    creditText: 'PromptQuorum',
    copyrightNotice: '© 2026 PromptQuorum. All rights reserved.',
  }
}
